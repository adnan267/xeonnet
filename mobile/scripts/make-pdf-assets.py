"""Packs the logo, seal, fonts and certificate CSS (from the website) into src/lib/pdfAssets.ts,
so PDFs made on the phone look exactly like the website and work offline.
Run again whenever frontend/app/certificate.css or the images change:  python3 scripts/make-pdf-assets.py"""
import base64, io, json, re
from PIL import Image
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FE = ROOT.parent / "frontend"
b64 = lambda p: base64.b64encode(Path(p).read_bytes()).decode()

def small_png(p, width):
    im = Image.open(p).convert("RGBA")
    im = im.resize((width, round(im.height * width / im.width)), Image.LANCZOS)
    buf = io.BytesIO(); im.save(buf, "PNG", optimize=True)
    return base64.b64encode(buf.getvalue()).decode()


css = (FE / "app/certificate.css").read_text()
css = css.split("/* screen preview inside the staff panel")[0]          # page styles only
for m in set(re.findall(r'url\("/fonts/cert/([^"]+)"\)', css)):
    css = css.replace(f'url("/fonts/cert/{m}")', f'url(data:font/woff2;base64,{b64(FE / "public/fonts/cert" / m)})')
out = {
    "LOGO": "data:image/png;base64," + small_png(FE / "public/img/logo-full-light.png", 480),
    "SEAL": "data:image/svg+xml;base64," + b64(FE / "public/img/cert-seal.svg"),
    "CERT_CSS": css,
}
ts = "// Generated by scripts/make-pdf-assets.py — do not edit by hand.\n" + "".join(
    f"export const {k} = {json.dumps(v)};\n" for k, v in out.items())
(ROOT / "src/lib/pdfAssets.ts").write_text(ts)
print("pdfAssets.ts", round(len(ts) / 1024), "KB")
